"""梦核旷野图（L_Dreamfield）的地面高度函数，Blender 生成地面网格、UE 搭图撒草、截图定机位三处共用这一份（米，UE 坐标，墙面在 X=+300、朝 -X）。
- 场地里近乎平坦：±0.6 米的细微起伏（波长 20–30 米）。
- 丘陵（用户 10-31：「另外旷野可以有少量的丘陵」）：圆润的余弦鼓包，场地里 5 座矮丘（高 5–9 米、半径 40–90 米、坡度不超过约 12°），
  都放在两翼和远处，平台正前方（X > -60、|Y| < 240）留一条开阔的主战场；场地外 10 座更大更缓的丘陵（高 10–30 米、半径 150–500 米）铺到地平线。
- 场地外再叠一层很缓的大起伏（±7 米，波长 500–900 米）。
- 墙脚 80 米内全部压平（平台、坡道、墙都立在平地上）。
"""
import math

WALL_X = 300.0
# (中心 x, 中心 y, 高, x 半径, y 半径, 转角°)
HILLS = [
    # 场地里（X -300~300、Y -450~450），避开平台正前方
    (-175.0, 265.0, 9.0, 85.0, 60.0, 20.0),
    (-70.0, -330.0, 7.0, 75.0, 52.0, -30.0),
    (-265.0, -45.0, 5.0, 60.0, 95.0, 0.0),
    (115.0, 390.0, 6.0, 60.0, 42.0, 10.0),
    (100.0, -405.0, 5.0, 55.0, 45.0, -15.0),
    # 场地外，铺到地平线
    (-660.0, 320.0, 14.0, 170.0, 125.0, 15.0),
    (-900.0, -520.0, 18.0, 230.0, 160.0, -20.0),
    (-520.0, -930.0, 12.0, 190.0, 140.0, 40.0),
    (-1320.0, 220.0, 22.0, 300.0, 220.0, 5.0),
    (-420.0, 930.0, 10.0, 160.0, 120.0, -10.0),
    (-1850.0, -720.0, 25.0, 380.0, 260.0, 30.0),
    (120.0, 1150.0, 12.0, 210.0, 150.0, 0.0),
    (80.0, -1250.0, 14.0, 230.0, 160.0, 15.0),
    (-2650.0, 950.0, 30.0, 500.0, 350.0, -25.0),
    (-3300.0, -1600.0, 28.0, 520.0, 380.0, 10.0),
]


def hills(x, y):
    h = 0.0
    for cx, cy, hh, rx, ry, rot in HILLS:
        a = math.radians(rot)
        dx, dy = x - cx, y - cy
        u = (dx * math.cos(a) + dy * math.sin(a)) / rx
        v = (-dx * math.sin(a) + dy * math.cos(a)) / ry
        d = math.sqrt(u * u + v * v)
        if d < 1.0:
            h += hh * 0.5 * (1.0 + math.cos(math.pi * d))
    return h


def height(x, y):
    r = max(max(abs(y) - 520.0, 0.0), max(-x - 380.0, 0.0))     # 离场地边多远
    far = min(max(r / 700.0, 0.0), 1.0)
    far = far * far * (3 - 2 * far)
    near = 0.35 * math.sin(x / 31.0 + 0.7) * math.cos(y / 27.0 + 1.3) + 0.25 * math.sin((x + 0.6 * y) / 23.0 + 2.1)
    big = (4.0 * math.sin(x / 140.0 + 0.4) * math.cos(y / 170.0 - 0.8) + 2.5 * math.sin((0.7 * x - y) / 110.0 + 1.9)
           + 1.2 * math.cos((x + y) / 63.0))
    h = near * (1 - far) + big * far + hills(x, y)
    flat = min(max((x - (WALL_X - 140.0)) / 60.0, 0.0), 1.0)    # 墙脚：平台前 70 米开始压平
    flat = flat * flat * (3 - 2 * flat)
    return h * (1 - flat)
